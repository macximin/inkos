export type StringKey = keyof typeof strings;
export type TFunction = (key: StringKey) => string;

export function useI18n() {
  const { data } = useApi<{ language: string }>("/project");
  const [lang, setLang] = useState<UiLanguage>(() => {
    if (typeof window === "undefined") return "zh";
    const saved = window.localStorage.getItem(UI_LANGUAGE_STORAGE_KEY);
    if (saved === "zh" || saved === "ko" || saved === "en") return saved;
    return window.navigator.language.toLowerCase().startsWith("ko") ? "ko" : "zh";
  });

  useEffect(() => {
    if (typeof window === "undefined" || window.localStorage.getItem(UI_LANGUAGE_STORAGE_KEY)) return;
    if (data?.language === "en") setLang("en");
  }, [data?.language]);

  function setUiLanguage(next: UiLanguage): void {
    window.localStorage.setItem(UI_LANGUAGE_STORAGE_KEY, next);
    setLang(next);
  }

  function t(key: StringKey): string {
    const translation = strings[key] as Translation;
    if (lang === "ko") return koreanOverrides[key] ?? translation.ko ?? translation.en;
    return translation[lang] ?? translation.zh;
  }

  return { t, lang, setUiLanguage };
}
